#!/bin/bash
# Builds tests/stubs/world.gd from the decompiled game, so the tests run the game's own _instance_actor (the function
# that creates and limits actors) and link the mod into the decompiled game project. Nothing from the game is stored
# in this repo.
#   GAME=/path/to/decompiled/webfishing ./tests/make_stubs.sh
set -e
cd "$(dirname "$0")"
GAME=${GAME:-/home/claude/wf-game/decomp}
G=$GAME/Scenes/World/world.gd
[ -f "$G" ] || { echo "decompiled game not found at $GAME (set GAME=...)"; exit 1; }
mkdir -p stubs
fn() { awk -v name="$1" '$0 ~ "^func "name"\\(" {p=1} p && /^func / && $0 !~ "^func "name"\\(" {p=0} p' "$G"; }
{
cat <<'HEAD'
extends Node
# TEST STUB (generated by make_stubs.sh): the header is hand written; _instance_actor is copied from the game's world.gd.
const ACTOR_BANK = {
	"aqua_fish": [preload("res://Scenes/Entities/AquaFish/aqua_fish.tscn"), false, 1],
}
var entities
var active_zone = "aquarium_zone"
var active_zone_owner = - 1
func _ready():
	entities = Spatial.new()
	add_child(entities)
	Network.connect("_instance_actor", self, "_instance_actor")
HEAD
fn _instance_actor
} > stubs/world.gd
# the mod, where the game would load it from (with AQ_PCK set the built pck is mounted instead, see run.sh)
if [ -n "$AQ_PCK" ]; then
  rm -f "$GAME/mods/Aquarium"
  echo "stubs written, the mod comes from $AQ_PCK"
else
  mkdir -p "$GAME/mods"
  ln -sfn "$(cd .. && pwd)/source/mods/Aquarium" "$GAME/mods/Aquarium"
  echo "stubs written, mod linked into $GAME/mods"
fi
